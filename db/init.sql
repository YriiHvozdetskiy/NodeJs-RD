-- Postgres виконує все з /docker-entrypoint-initdb.d/ РІВНО ОДИН РАЗ — при
-- першій ініціалізації порожнього тому даних:
--   docker compose down     → том лишається → цей файл більше не запуститься
--   docker compose down -v  → том знищено   → наступний up виконає його наново
--
-- Пароля тут НЕМАЄ навмисно, і це не недбалість. Роль без пароля не може
-- залогінитись узагалі — тобто не існує вікна, коли база доступна з
-- «дефолтним» значенням, і не існує другого джерела правди, яке могло б
-- розійтися з файлом-секретом. Пароль ставить scripts/db-up.sh одразу після
-- підйому: ALTER ROLE зі вмісту secrets/db_password. Той самий ALTER робить
-- старт ідемпотентним після `down -v`: том знищено, роль знову без пароля,
-- а файл лишився з ротованим значенням — db-up.sh їх вирівнює.
CREATE ROLE app_user LOGIN;

GRANT CONNECT ON DATABASE marketplace TO app_user;

