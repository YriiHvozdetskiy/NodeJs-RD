-- Postgres виконує все з /docker-entrypoint-initdb.d/ РІВНО ОДИН РАЗ — при
-- першій ініціалізації порожнього тому даних:
--   docker compose down     → том лишається → цей файл більше не запуститься
--   docker compose down -v  → том знищено   → наступний up виконає його наново
--
-- Звідси пастка ротації: після `down -v` роль повертається до пароля нижче,
-- а secrets/db_password лишається з ротованим значенням, і застосунок падає з
-- «password authentication failed». Тому `scripts/db-up.sh` після підйому
-- ВИРІВНЮЄ пароль ролі зі вмістом файла, і старт лишається ідемпотентним.

-- Роль застосунку. Стартовий пароль збігається з тим, що кладе у файл-секрет
-- scripts/db-up.sh. rotate.sh цього значення не пише — він щоразу генерує нове.
CREATE ROLE app_user LOGIN PASSWORD 'app-v1-password';

GRANT CONNECT ON DATABASE marketplace TO app_user;

