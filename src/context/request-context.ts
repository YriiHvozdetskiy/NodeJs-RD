import { AsyncLocalStorage } from 'node:async_hooks';
import { randomUUID } from 'node:crypto';

/** Те, що живе в контексті запиту. Поки лише id, на Л#29 сюди прийде трасування. */
export interface RequestStore {
  readonly requestId: string;
}

/**
 * Сховище, привʼязане до ланцюжка асинхронних викликів.
 *
 * ⚠ ЧОМУ НЕ ГЛОБАЛЬНА ЗМІННА — головне питання цього ДЗ.
 *
 * На фронті глобал працював би: вкладка одна, користувач один, і поки ви
 * чекаєте `await fetch()`, ніхто інший вашу змінну не чіпає. На сервері все
 * навпаки. Поки запит A стоїть на `await db.query()`, event loop не простоює —
 * він бере наступний запит B і виконує його синхронний шматок. B перезаписує
 * глобал своїм id. Коли A прокидається і йде логувати, у глобалі вже id від B.
 *
 * Це не гіпотетика: воно ламається саме під навантаженням і саме в логах, тобто
 * тоді, коли логи потрібні найбільше. Один запит падає — а requestId у трейсі
 * веде на зовсім інший, успішний.
 *
 * AsyncLocalStorage тримає окреме сховище для кожного ланцюжка await'ів.
 * Механізм під ним — async_hooks: Node і так відстежує кожну асинхронну
 * операцію, щоб знати, коли її виконувати; ALS просто вішає на це відстеження
 * свою скриньку.
 *
 * Найближча аналогія з фронту — React context: компонент на десятому рівні
 * вкладеності бере значення, і батькам не треба передавати його пропсами крізь
 * усі проміжні. Де аналогія тріскається: React context — це дерево В ПАМʼЯТІ,
 * і воно одне на застосунок. Тут вимірів два — глибина стека І паралельні
 * запити, — і кожен запит отримує своє дерево.
 */
const storage = new AsyncLocalStorage<RequestStore>();

/**
 * Виконує `callback` усередині контексту запиту.
 *
 * Має обгортати ВЕСЬ обробник. Якщо запустити його всередині, скажімо, лише
 * хендлера, то middleware й guard опиняться поза контекстом, і `getRequestId()`
 * там поверне undefined.
 */
export function runWithContext<T>(store: RequestStore, callback: () => T): T {
  return storage.run(store, callback);
}

/**
 * Дістає id поточного запиту з будь-якої глибини стека.
 *
 * Саме заради цього рядка існує все вище: сервіс, репозиторій чи логер беруть
 * id, не отримуючи його параметром. Інакше `requestId` довелося б протягувати
 * крізь кожну сигнатуру аж до останнього виклику — і перша ж функція, яка його
 * забула прокинути, обриває трасування.
 */
export function getRequestId(): string | undefined {
  return storage.getStore()?.requestId;
}

/**
 * Id для нового запиту: беремо клієнтський, якщо він є, інакше свій.
 *
 * Клієнтський у пріоритеті навмисно — так id живе наскрізь через кілька
 * сервісів, і в розподіленій системі можна зшити лог фронту з логом бекенду.
 */
export function resolveRequestId(header: string | string[] | undefined): string {
  if (typeof header === 'string' && header.trim() !== '') {
    return header.trim();
  }
  // Масив трапляється, коли заголовок надіслали двічі — беремо перший.
  if (Array.isArray(header) && header.length > 0) {
    return header[0];
  }
  return randomUUID();
}
