import { z } from 'zod';

/**
 * Контракт тіла `POST /users` — тепер Zod-схема, а не клас із декораторами.
 *
 * Що змінилось порівняно з ДЗ#7 і чому це не просто «інша бібліотека»:
 *
 * `class-validator` тримав правила В МЕТАДАНИХ, окремо від типу. Тип писався
 * руками (`email!: string`), правила вішались декораторами, і ніщо не заважало
 * їм розʼїхатись: `@IsInt() name!: string` компілювався б без слова.
 *
 * У Zod схема — це ЄДИНЕ джерело. Тип виводиться з неї через `z.infer`, тож
 * розʼїхатись фізично нема чому: додали поле в схему — воно зʼявилось у типі.
 *
 * Ціна: результат — plain-обʼєкт, а не екземпляр класу. `instanceof` більше не
 * працює, і це нормально — перевіряти треба форму даних, а не їхній конструктор.
 */
export const createUserSchema = z.object({
  name: z.string().min(2, 'name має бути щонайменше 2 символи'),
  email: z.email('email має бути коректною адресою'),
  age: z.int().min(16, 'age має бути не менше 16'),
  // strict() — те саме, що whitelist у ДЗ#7, але суворіше: зайве поле не
  // вирізається мовчки, а дає помилку. Для вхідного контракту це чесніше —
  // клієнт дізнається, що його `role: "admin"` не прийняли, а не гадатиме,
  // чому воно не спрацювало.
}).strict();

/** Тип виводиться зі схеми — окремо його ніхто не пише і не підтримує. */
export type CreateUserDto = z.infer<typeof createUserSchema>;
