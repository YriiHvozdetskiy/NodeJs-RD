import 'reflect-metadata';

import { INJECT_TOKENS } from '../tokens';
import type { MaybeForwardRef } from '../types';

/**
 * Явний токен для параметра конструктора.
 *
 * Потрібен там, де типу недостатньо. Інтерфейс у метаданих перетворюється на
 * `Object`, бо в рантаймі інтерфейсів не існує — це стирання типів, а не
 * обмеження нашої реалізації. Те саме з рядком, числом і літеральним обʼєктом:
 * `String` як тип нічого не каже про те, ЯКИЙ саме рядок треба підставити.
 *
 * Параметр-декоратор отримує три аргументи: (target, propertyKey, parameterIndex).
 * Для параметра КОНСТРУКТОРА `propertyKey === undefined` — саме цим він
 * відрізняється від параметра методу.
 *
 * ⚠ Порядок виконання: параметр-декоратори відпрацьовують ЗВЕРХУ ВНИЗ по файлу,
 * але в межах одного списку параметрів — від останнього до першого (n-1 → 0),
 * і всі вони — ДО декоратора самого класу. Тобто на момент, коли спрацює
 * @Injectable(), мапа токенів на класі вже лежить.
 *
 * Зберігаємо розріджену мапу `індекс -> токен`, а не масив: @Inject стоїть
 * лише на частині параметрів, і саме індекс — єдиний ключ, який пережив
 * компіляцію. Розрізнити два параметри за типом неможливо: обидва `Object`.
 */
export function Inject(token: MaybeForwardRef): ParameterDecorator {
  return (target, _propertyKey, parameterIndex) => {
    // getOwnMetadata, а не getMetadata — критично. getMetadata ходить по
    // ланцюгу прототипів і повертає мапу батька ЗА ПОСИЛАННЯМ; дозапис
    // нижче мутував би її на місці й дописав чужий токен у батьківський клас.
    const map: Record<number, MaybeForwardRef> = Reflect.getOwnMetadata(INJECT_TOKENS, target) ?? {};

    // Саме дозапис, а не заміна: параметр-декоратори спрацьовують по одному
    // (у зворотному порядку індексів), і `defineMetadata` з новим обʼєктом
    // затер би все, що записали попередні.
    map[parameterIndex] = token;

    Reflect.defineMetadata(INJECT_TOKENS, map, target);
  };
}
