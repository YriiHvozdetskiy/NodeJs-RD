#!/usr/bin/env bash
# Сходинка 2 конвеєра (#32): контракт — чи ламає нова спека тих, хто вже живе на старій.
#
#   bash scripts/gates/contract.sh <спека-бази> <спека-голови>
#
# У CI база — openapi/openapi.yaml з коміту бази PR, голова — зі змін PR.
# demo:gates дає сюди похідні від тієї самої спеки: сумісну (додано шлях) і
# ламаючу (прибрано операцію).
#
# Pact (#16) ловить поломку для споживача, якого ми знаємо й чий контракт
# записано. oasdiff порівнює саму спеку — і ловить поломку для того, кого ми не
# знаємо: мобільного клієнта на старій версії, інтеграцію партнера.
#
# --fail-on ERR: код 1 лише на змінах рівня error (прибрана операція,
# обовʼязкове поле зникло з відповіді, новий обовʼязковий параметр). Додані
# шляхи й необовʼязкові поля — рівень info, вони гейт не валять.
set -euo pipefail

BASE="${1:?спека бази}"; HEAD="${2:?спека голови}"
OASDIFF_IMAGE="${OASDIFF_IMAGE:-tufin/oasdiff:v1.32.1}"

abs() { (cd "$(dirname "$1")" && printf '%s/%s' "$(pwd)" "$(basename "$1")"); }
BASE="$(abs "${BASE}")"; HEAD="$(abs "${HEAD}")"

# Обидва файли — read-only томами; розширення зберігаємо, бо за ним oasdiff
# вирішує, YAML це чи JSON. Мережа контейнеру не потрібна.
IN_BASE="/specs/base.${BASE##*.}"; IN_HEAD="/specs/head.${HEAD##*.}"
docker run --rm --network none \
  -v "${BASE}:${IN_BASE}:ro" \
  -v "${HEAD}:${IN_HEAD}:ro" \
  "${OASDIFF_IMAGE}" breaking "${IN_BASE}" "${IN_HEAD}" --fail-on ERR
